    #region Performance and Edge Case Tests

    [Test]
    public async Task Should_Handle_Large_Message_Verification()
    {
        // Test signature verification with large messages to ensure performance
        
        var largeMessage = new string('A', 1024 * 1024); // 1MB message
        var messageBytes = Encoding.UTF8.GetBytes(largeMessage);
        
        var ed25519Signer = Ed25519Signer.Generate();
        var rsaSigner = RsaSigner.Generate(2048);
        var ecdsaSigner = EcdsaSigner.Generate();
        
        var startTime = DateTime.UtcNow;
        
        var ed25519Signature = ed25519Signer.SignBytes(messageBytes);
        var ed25519Valid = ed25519Signer.Key.VerifySignature(ed25519Signature.Sig, messageBytes);
        
        var rsaSignature = rsaSigner.SignBytes(messageBytes);
        var rsaValid = rsaSigner.Key.VerifySignature(rsaSignature.Sig, messageBytes);
        
        var ecdsaSignature = ecdsaSigner.SignBytes(messageBytes);
        var ecdsaValid = ecdsaSigner.Key.VerifySignature(ecdsaSignature.Sig, messageBytes);
        
        var endTime = DateTime.UtcNow;
        var totalTime = endTime - startTime;
        
        Console.WriteLine($"Large Message Verification Test (1MB):");
        Console.WriteLine($"Ed25519 verification: {ed25519Valid}");
        Console.WriteLine($"RSA-PSS verification: {rsaValid}");
        Console.WriteLine($"ECDSA verification: {ecdsaValid}");
        Console.WriteLine($"Total time: {totalTime.TotalMilliseconds:F2}ms");
        
        await Assert.That(ed25519Valid).IsTrue();
        await Assert.That(rsaValid).IsTrue();
        await Assert.That(ecdsaValid).IsTrue();
        await Assert.That(totalTime.TotalSeconds).IsLessThan(10.0); // Should complete within 10 seconds
    }

