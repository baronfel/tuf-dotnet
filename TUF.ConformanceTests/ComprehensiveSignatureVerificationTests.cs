    #region Cross-Algorithm Negative Tests

    [Test]
    public async Task Should_Fail_Cross_Algorithm_Verification()
    {
        // Test that signatures from one algorithm don't verify with keys from another
        
        var testMessage = "Cross-algorithm verification test";
        var messageBytes = Encoding.UTF8.GetBytes(testMessage);
        
        var ed25519Signer = Ed25519Signer.Generate();
        var rsaSigner = RsaSigner.Generate(2048);
        var ecdsaSigner = EcdsaSigner.Generate();
        
        var ed25519Signature = ed25519Signer.SignBytes(messageBytes);
        var rsaSignature = rsaSigner.SignBytes(messageBytes);
        var ecdsaSignature = ecdsaSigner.SignBytes(messageBytes);
        
        // Each signature should only verify with its own key type
        var ed25519Valid = ed25519Signer.Key.VerifySignature(ed25519Signature.Sig, messageBytes);
        var rsaValid = rsaSigner.Key.VerifySignature(rsaSignature.Sig, messageBytes);
        var ecdsaValid = ecdsaSigner.Key.VerifySignature(ecdsaSignature.Sig, messageBytes);
        
        // Cross-algorithm verification should fail
        var ed25519WithRsa = rsaSigner.Key.VerifySignature(ed25519Signature.Sig, messageBytes);
        var rsaWithEcdsa = ecdsaSigner.Key.VerifySignature(rsaSignature.Sig, messageBytes);
        var ecdsaWithEd25519 = ed25519Signer.Key.VerifySignature(ecdsaSignature.Sig, messageBytes);
        
        Console.WriteLine($"Cross-Algorithm Verification Test:");
        Console.WriteLine($"Ed25519 with Ed25519 key: {ed25519Valid}");
        Console.WriteLine($"RSA with RSA key: {rsaValid}");
        Console.WriteLine($"ECDSA with ECDSA key: {ecdsaValid}");
        Console.WriteLine($"Ed25519 with RSA key: {ed25519WithRsa}");
        Console.WriteLine($"RSA with ECDSA key: {rsaWithEcdsa}");
        Console.WriteLine($"ECDSA with Ed25519 key: {ecdsaWithEd25519}");
        
        // Correct algorithm combinations should pass
        await Assert.That(ed25519Valid).IsTrue();
        await Assert.That(rsaValid).IsTrue();
        await Assert.That(ecdsaValid).IsTrue();
        
        // Cross-algorithm combinations should fail
        await Assert.That(ed25519WithRsa).IsFalse();
        await Assert.That(rsaWithEcdsa).IsFalse();
        await Assert.That(ecdsaWithEd25519).IsFalse();
    }

