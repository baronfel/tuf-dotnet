    [Test]
    public async Task ECDSA_P256_Should_Verify_Multiple_Signatures()
    {
        // Test that ECDSA generates different signatures for the same message
        // but all verify correctly (non-deterministic behavior)
        
        var testMessage = "ECDSA non-deterministic signature test";
        var messageBytes = Encoding.UTF8.GetBytes(testMessage);
        
        var signer = EcdsaSigner.Generate();
        
        // Generate multiple signatures for the same message
        var signature1 = signer.SignBytes(messageBytes);
        var signature2 = signer.SignBytes(messageBytes);
        var signature3 = signer.SignBytes(messageBytes);
        
        // All signatures should be different (with high probability)
        var allDifferent = signature1.Sig != signature2.Sig && 
                          signature2.Sig != signature3.Sig && 
                          signature1.Sig != signature3.Sig;
        
        // But all should verify correctly
        var sig1Valid = signer.Key.VerifySignature(signature1.Sig, messageBytes);
        var sig2Valid = signer.Key.VerifySignature(signature2.Sig, messageBytes);
        var sig3Valid = signer.Key.VerifySignature(signature3.Sig, messageBytes);
        
        Console.WriteLine($"ECDSA P-256 Non-Deterministic Test:");
        Console.WriteLine($"Signature 1: {signature1.Sig[..32]}...");
        Console.WriteLine($"Signature 2: {signature2.Sig[..32]}...");
        Console.WriteLine($"Signature 3: {signature3.Sig[..32]}...");
        Console.WriteLine($"All different: {allDifferent}");
        Console.WriteLine($"All valid: {sig1Valid && sig2Valid && sig3Valid}");
        
        await Assert.That(allDifferent).IsTrue();
        await Assert.That(sig1Valid).IsTrue();
        await Assert.That(sig2Valid).IsTrue();
        await Assert.That(sig3Valid).IsTrue();
    }

