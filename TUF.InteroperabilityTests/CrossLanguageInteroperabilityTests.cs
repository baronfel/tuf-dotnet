    private async Task ExportKeyAndSignatureForExternalVerification(
        string keyType, 
        Key key, 
        SignatureObject signature, 
        byte[] testData)
    {
        // Export key and signature data in a format that can be used by Python/Go verification scripts
        
        var exportDir = Path.Combine(TestFixturesPath, "cross-verification", keyType);
        Directory.CreateDirectory(exportDir);
        
        var exportData = new
        {
            key_type = key.KeyType,
            key_scheme = key.Scheme,
            public_key = key.KeyVal.Public,
            key_id = key.GetKeyId(),
            signature = signature.Sig,
            test_data = Convert.ToBase64String(testData),
            test_data_utf8 = System.Text.Encoding.UTF8.GetString(testData)
        };
        
        var exportPath = Path.Combine(exportDir, $"dotnet-{keyType}-export.json");
        var exportJson = JsonSerializer.Serialize(exportData, new JsonSerializerOptions 
        { 
            WriteIndented = true 
        });
        
        await File.WriteAllTextAsync(exportPath, exportJson);
        Console.WriteLine($"Exported {keyType} key and signature data to: {exportPath}");
    }

    private async Task TestPythonCanReadRepository(string repositoryPath)
    {
        // Use Python TUF to validate the .NET-generated repository
        Console.WriteLine("Testing if Python TUF client can read .NET repository...");
        
        var pythonScript = Path.Combine(TestFixturesPath, "scripts", "test_python_can_read_dotnet.py");
        
        if (!File.Exists(pythonScript))
        {
            Console.WriteLine($"Python validation script not found: {pythonScript}");
            Console.WriteLine("Skipping Python interoperability validation");
            return;
        }
        
        try
        {
            var startInfo = new ProcessStartInfo
            {
                FileName = "python3",
                Arguments = $"\"{pythonScript}\" \"{repositoryPath}\"",
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true
            };
            
            using var process = Process.Start(startInfo);
            if (process == null)
            {
                Console.WriteLine("Could not start Python process");
                return;
            }
            
            var output = await process.StandardOutput.ReadToEndAsync();
            var error = await process.StandardError.ReadToEndAsync();
            
            await process.WaitForExitAsync();
            
            Console.WriteLine($"Python validation output: {output}");
            if (!string.IsNullOrEmpty(error))
            {
                Console.WriteLine($"Python validation error: {error}");
            }
            
            if (process.ExitCode == 0)
            {
                Console.WriteLine("✅ Python TUF client successfully validated .NET repository");
            }
            else
            {
                Console.WriteLine($"❌ Python TUF client failed to validate .NET repository (exit code: {process.ExitCode})");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Could not run Python validation: {ex.Message}");
            Console.WriteLine("This may indicate Python or python-tuf is not installed");
        }
    }

    private async Task TestGoCanReadRepository(string repositoryPath)
    {
        // Use Go TUF to validate the .NET-generated repository
        Console.WriteLine("Testing if Go TUF client can read .NET repository...");
        
        var goScript = Path.Combine(TestFixturesPath, "scripts", "test_go_can_read_dotnet.go");
        
        if (!File.Exists(goScript))
        {
            Console.WriteLine($"Go validation script not found: {goScript}");
            Console.WriteLine("Skipping Go interoperability validation");
            return;
        }
        
        try
        {
            // First compile the Go script
            var compileStartInfo = new ProcessStartInfo
            {
                FileName = "go",
                Arguments = $"build -o test_go_reader \"{goScript}\"",
                WorkingDirectory = Path.GetDirectoryName(goScript),
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true
            };
            
            using var compileProcess = Process.Start(compileStartInfo);
            if (compileProcess != null)
            {
                await compileProcess.WaitForExitAsync();
                if (compileProcess.ExitCode != 0)
                {
                    var compileError = await compileProcess.StandardError.ReadToEndAsync();
                    Console.WriteLine($"Go compilation failed: {compileError}");
                    return;
                }
            }
            
            // Run the compiled Go program
            var runStartInfo = new ProcessStartInfo
            {
                FileName = Path.Combine(Path.GetDirectoryName(goScript)!, "test_go_reader"),
                Arguments = $"\"{repositoryPath}\"",
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true
            };
            
            using var runProcess = Process.Start(runStartInfo);
            if (runProcess == null)
            {
                Console.WriteLine("Could not start Go process");
                return;
            }
            
            var output = await runProcess.StandardOutput.ReadToEndAsync();
            var error = await runProcess.StandardError.ReadToEndAsync();
            
            await runProcess.WaitForExitAsync();
            
            Console.WriteLine($"Go validation output: {output}");
            if (!string.IsNullOrEmpty(error))
            {
                Console.WriteLine($"Go validation error: {error}");
            }
            
            if (runProcess.ExitCode == 0)
            {
                Console.WriteLine("✅ Go TUF client successfully validated .NET repository");
            }
            else
            {
                Console.WriteLine($"❌ Go TUF client failed to validate .NET repository (exit code: {runProcess.ExitCode})");
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Could not run Go validation: {ex.Message}");
            Console.WriteLine("This may indicate Go or go-tuf is not installed");
        }
    }
