    [Test] 
    public async Task Python_Client_Can_Read_DotNet_Repository()
    {
        // Test that a Python TUF client can read a repository created by .NET TUF
        
        // First, create a .NET TUF repository
        var tempDir = Path.GetTempPath();
        var dotnetRepoPath = Path.Combine(tempDir, "dotnet-tuf-repo-for-python", Guid.NewGuid().ToString());
        Directory.CreateDirectory(dotnetRepoPath);

        try
        {
            Console.WriteLine($"Creating .NET TUF repository at: {dotnetRepoPath}");
            
            // Create a simple repository using .NET TUF
            var repositoryBuilder = new RepositoryBuilder();
            
            // Add signers for all roles
            var rootSigner = Ed25519Signer.Generate();
            var timestampSigner = Ed25519Signer.Generate(); 
            var snapshotSigner = Ed25519Signer.Generate();
            var targetsSigner = Ed25519Signer.Generate();
            
            repositoryBuilder
                .AddSigner("root", rootSigner)
                .AddSigner("timestamp", timestampSigner)
                .AddSigner("snapshot", snapshotSigner)
                .AddSigner("targets", targetsSigner);

            // Add a simple target file
            var testContent = "Hello from .NET TUF repository!"u8.ToArray();
            repositoryBuilder.AddTarget("test-file.txt", testContent);
            
            // Build and write the repository
            var repository = repositoryBuilder.Build();
            repository.WriteToDirectory(dotnetRepoPath);
            
            Console.WriteLine("✅ Successfully created .NET TUF repository");
            Console.WriteLine($"Repository structure:");
            foreach (var file in Directory.GetFiles(dotnetRepoPath, "*", SearchOption.AllDirectories))
            {
                var relativePath = Path.GetRelativePath(dotnetRepoPath, file);
                Console.WriteLine($"  - {relativePath} ({new FileInfo(file).Length} bytes)");
            }

            // Now test if Python can read it
            await TestPythonCanReadRepository(dotnetRepoPath);
        }
        finally
        {
            // Clean up temporary directory
            try
            {
                if (Directory.Exists(dotnetRepoPath))
                {
                    Directory.Delete(dotnetRepoPath, recursive: true);
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Warning: Could not clean up temporary directory {dotnetRepoPath}: {ex.Message}");
            }
        }
    }

