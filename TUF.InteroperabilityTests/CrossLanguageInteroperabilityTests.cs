    [Test]
    public async Task Cross_Implementation_Signature_Verification()
    {
        // Test that signatures created by one implementation can be verified by another
        
        Console.WriteLine("Testing cross-implementation signature verification...");
        
        // Test Ed25519 signatures
        await TestEd25519CrossVerification();
        
        // Test ECDSA signatures
        await TestEcdsaCrossVerification();
        
        // Test RSA signatures
        await TestRsaCrossVerification();
    }

    private async Task TestEd25519CrossVerification()
    {
        Console.WriteLine("Testing Ed25519 cross-implementation verification...");
        
        // Create a test key and signature using .NET TUF
        var signer = Ed25519Signer.Generate();
        var testData = "Cross-implementation Ed25519 test data"u8.ToArray();
        var signature = signer.SignBytes(testData);
        
        Console.WriteLine($"Created Ed25519 signature:");
        Console.WriteLine($"  - Key ID: {signature.KeyId}");
        Console.WriteLine($"  - Key Type: {signer.Key.KeyType}");
        Console.WriteLine($"  - Key Scheme: {signer.Key.Scheme}");
        Console.WriteLine($"  - Public Key Length: {signer.Key.KeyVal.Public.Length}");
        Console.WriteLine($"  - Signature Length: {signature.Sig.Length}");
        
        // Verify the signature with our own implementation first
        var verificationResult = signer.Key.VerifySignature(signature.Sig, testData);
        await Assert.That(verificationResult).IsTrue();
        
        Console.WriteLine("✅ Ed25519 self-verification successful");
        
        // Export key and signature data for external verification by Python/Go
        await ExportKeyAndSignatureForExternalVerification("ed25519", signer.Key, signature, testData);
    }

    private async Task TestEcdsaCrossVerification()
    {
        Console.WriteLine("Testing ECDSA cross-implementation verification...");
        
